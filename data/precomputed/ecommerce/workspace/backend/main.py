# E-Commerce Platform - Main Application Entrypoint
from fastapi import FastAPI, Depends, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from typing import List
import os

from backend.routes import products, orders, auth

app = FastAPI(
    title="E-Commerce Platform API",
    description="Production API generated by AI Product Architect for: Build an e-commerce platform with product listings, categories, product search, ...",
    version="1.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(products.router, prefix="/api/products", tags=["Product Management"])
app.include_router(orders.router, prefix="/api/orders", tags=["Order Management"])
app.include_router(auth.router, prefix="/api/auth", tags=["Authentication"])

@app.get("/health")
def health_check():
    return {"status": "healthy", "service": "E-Commerce Platform", "version": "1.0.0"}

@app.get("/")
def root():
    return {"message": "Welcome to E-Commerce Platform API", "docs_url": "/docs"}
