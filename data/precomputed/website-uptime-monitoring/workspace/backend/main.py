# Website Uptime Monitoring - Main Application Entrypoint
from fastapi import FastAPI, Depends, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from typing import List
import os

from backend.routes import monitoredurls, uptimechecks, auth

app = FastAPI(
    title="Website Uptime Monitoring API",
    description="Production API generated by AI Product Architect for: Build a website uptime monitoring system with website registration, health check...",
    version="1.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(monitoredurls.router, prefix="/api/monitoredurls", tags=["MonitoredUrl Management"])
app.include_router(monitoredurls.router, prefix="/api/monitors", tags=["Monitors Management"])
app.include_router(uptimechecks.router, prefix="/api/uptimechecks", tags=["UptimeCheck Management"])
app.include_router(auth.router, prefix="/api/auth", tags=["Authentication"])

@app.get("/health")
def health_check():
    return {"status": "healthy", "service": "Website Uptime Monitoring", "version": "1.0.0"}

@app.get("/")
def root():
    return {"message": "Welcome to Website Uptime Monitoring API", "docs_url": "/docs"}
