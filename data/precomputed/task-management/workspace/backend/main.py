# Task Management System - Main Application Entrypoint
from fastapi import FastAPI, Depends, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from typing import List
import os

from backend.routes import tasks, categories, auth

app = FastAPI(
    title="Task Management System API",
    description="Production API generated by AI Product Architect for: Build a task management application with user roles, projects, task assignments,...",
    version="1.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(tasks.router, prefix="/api/tasks", tags=["Task Management"])
app.include_router(categories.router, prefix="/api/categories", tags=["Category Management"])
app.include_router(auth.router, prefix="/api/auth", tags=["Authentication"])

@app.get("/health")
def health_check():
    return {"status": "healthy", "service": "Task Management System", "version": "1.0.0"}

@app.get("/")
def root():
    return {"message": "Welcome to Task Management System API", "docs_url": "/docs"}
