# Student Learning Management System - Main Application Entrypoint
from fastapi import FastAPI, Depends, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from typing import List
import os

from backend.routes import courses, enrollments, auth

app = FastAPI(
    title="Student Learning Management System API",
    description="Production API generated by AI Product Architect for: Build a student learning management system with students, instructors, courses, ...",
    version="1.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(courses.router, prefix="/api/courses", tags=["Course Management"])
app.include_router(enrollments.router, prefix="/api/enrollments", tags=["Enrollment Management"])
app.include_router(auth.router, prefix="/api/auth", tags=["Authentication"])

@app.get("/health")
def health_check():
    return {"status": "healthy", "service": "Student Learning Management System", "version": "1.0.0"}

@app.get("/")
def root():
    return {"message": "Welcome to Student Learning Management System API", "docs_url": "/docs"}
