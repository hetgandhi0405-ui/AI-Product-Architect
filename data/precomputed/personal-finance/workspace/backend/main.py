# Personal Finance Tracker - Main Application Entrypoint
from fastapi import FastAPI, Depends, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from typing import List
import os

from backend.routes import transactions, categories, auth

app = FastAPI(
    title="Personal Finance Tracker API",
    description="Production API generated by AI Product Architect for: Build a personal finance tracker with transactions, categories, budgets, monthly...",
    version="1.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(transactions.router, prefix="/api/transactions", tags=["Transaction Management"])
app.include_router(categories.router, prefix="/api/categories", tags=["Category Management"])
app.include_router(auth.router, prefix="/api/auth", tags=["Authentication"])

@app.get("/health")
def health_check():
    return {"status": "healthy", "service": "Personal Finance Tracker", "version": "1.0.0"}

@app.get("/")
def root():
    return {"message": "Welcome to Personal Finance Tracker API", "docs_url": "/docs"}
