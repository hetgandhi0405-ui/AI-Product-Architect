def generate_prompt_tailored_files(requirements: str, project_name: str, base_files: dict = None) -> Dict[str, str]:
    """
    Generate 100% production-grade, complete, syntax-error-free files tailored to customer requirements.
    Generates 17 complete project files spanning Frontend, Backend, Database, Docker, Infrastructure, and Testing.
    """
    req_lower = requirements.lower()
    files = dict(base_files) if base_files else {}

    if any(k in req_lower for k in ["event", "analytic", "metric", "stream", "sensor", "telemetry", "tracking"]):
        entity = "Event"
        entity_lower = "event"
        entity_plural = "events"
    elif any(k in req_lower for k in ["e-commerce", "ecommerce", "store", "shop", "product", "cart", "order", "book"]):
        entity = "Product"
        entity_lower = "product"
        entity_plural = "products"
