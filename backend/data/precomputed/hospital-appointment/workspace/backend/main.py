# Hospital Appointment System - Main Application Entrypoint
from fastapi import FastAPI, Depends, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from typing import List
import os

from backend.routes import doctors, patients, auth

app = FastAPI(
    title="Hospital Appointment System API",
    description="Production API generated by AI Product Architect for: Build a hospital appointment system with patient registration, doctor profiles, ...",
    version="1.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(doctors.router, prefix="/api/doctors", tags=["Doctor Management"])
app.include_router(patients.router, prefix="/api/patients", tags=["Patient Management"])
app.include_router(auth.router, prefix="/api/auth", tags=["Authentication"])

@app.get("/health")
def health_check():
    return {"status": "healthy", "service": "Hospital Appointment System", "version": "1.0.0"}

@app.get("/")
def root():
    return {"message": "Welcome to Hospital Appointment System API", "docs_url": "/docs"}
