# Real-Time Analytics Dashboard - Main Application Entrypoint
from fastapi import FastAPI, Depends, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from typing import List
import os

from backend.routes import events, streamsources, auth

app = FastAPI(
    title="Real-Time Analytics Dashboard API",
    description="Production API generated by AI Product Architect for: Build a real-time analytics dashboard with event ingestion, aggregation, time-ba...",
    version="1.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(events.router, prefix="/api/events", tags=["Event Management"])
app.include_router(streamsources.router, prefix="/api/streamsources", tags=["StreamSource Management"])
app.include_router(auth.router, prefix="/api/auth", tags=["Authentication"])

@app.get("/health")
def health_check():
    return {"status": "healthy", "service": "Real-Time Analytics Dashboard", "version": "1.0.0"}

@app.get("/")
def root():
    return {"message": "Welcome to Real-Time Analytics Dashboard API", "docs_url": "/docs"}
