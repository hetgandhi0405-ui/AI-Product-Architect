# Smart Home Dashboard - Main Application Entrypoint
from fastapi import FastAPI, Depends, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from typing import List
import os

from backend.routes import devices, sensorreadings, auth

app = FastAPI(
    title="Smart Home Dashboard API",
    description="Production API generated by AI Product Architect for: Build a smart home dashboard with rooms, devices, device status, monitoring, and...",
    version="1.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(devices.router, prefix="/api/devices", tags=["Device Management"])
app.include_router(sensorreadings.router, prefix="/api/sensorreadings", tags=["SensorReading Management"])
app.include_router(auth.router, prefix="/api/auth", tags=["Authentication"])

@app.get("/health")
def health_check():
    return {"status": "healthy", "service": "Smart Home Dashboard", "version": "1.0.0"}

@app.get("/")
def root():
    return {"message": "Welcome to Smart Home Dashboard API", "docs_url": "/docs"}
