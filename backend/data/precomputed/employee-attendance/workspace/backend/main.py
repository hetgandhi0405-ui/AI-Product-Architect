# Employee Attendance Management - Main Application Entrypoint
from fastapi import FastAPI, Depends, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from typing import List
import os

from backend.routes import employees, attendances, auth

app = FastAPI(
    title="Employee Attendance Management API",
    description="Production API generated by AI Product Architect for: Build an employee attendance management system with employee records, check-in/c...",
    version="1.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(employees.router, prefix="/api/employees", tags=["Employee Management"])
app.include_router(attendances.router, prefix="/api/attendances", tags=["Attendance Management"])
app.include_router(auth.router, prefix="/api/auth", tags=["Authentication"])

@app.get("/health")
def health_check():
    return {"status": "healthy", "service": "Employee Attendance Management", "version": "1.0.0"}

@app.get("/")
def root():
    return {"message": "Welcome to Employee Attendance Management API", "docs_url": "/docs"}
