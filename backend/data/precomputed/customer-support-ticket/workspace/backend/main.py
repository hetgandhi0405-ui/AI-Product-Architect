# Customer Support Ticket System - Main Application Entrypoint
from fastapi import FastAPI, Depends, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from typing import List
import os

from backend.routes import tickets, departments, auth

app = FastAPI(
    title="Customer Support Ticket System API",
    description="Production API generated by AI Product Architect for: Build a customer support ticket system with ticket creation, assignment, priorit...",
    version="1.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(tickets.router, prefix="/api/tickets", tags=["Ticket Management"])
app.include_router(departments.router, prefix="/api/departments", tags=["Department Management"])
app.include_router(auth.router, prefix="/api/auth", tags=["Authentication"])

@app.get("/health")
def health_check():
    return {"status": "healthy", "service": "Customer Support Ticket System", "version": "1.0.0"}

@app.get("/")
def root():
    return {"message": "Welcome to Customer Support Ticket System API", "docs_url": "/docs"}
